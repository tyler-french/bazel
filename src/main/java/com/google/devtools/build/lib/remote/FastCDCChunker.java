  private final int minSize;
  private final int maxSize;
  private final int avgSize;
  private final long maskS;
  private final long maskL;
  private final DigestUtil digestUtil;

  public FastCDCChunker(DigestUtil digestUtil) {
    this(
        RemoteOptions.CHUNKING_MIN_SIZE,
        RemoteOptions.CHUNKING_AVERAGE_SIZE,
        RemoteOptions.CHUNKING_MAX_SIZE,
        RemoteOptions.CHUNKING_NORMALIZATION_LEVEL,
        digestUtil);
  }

  public FastCDCChunker(int minSize, int avgSize, int maxSize, DigestUtil digestUtil) {
    this(minSize, avgSize, maxSize, RemoteOptions.CHUNKING_NORMALIZATION_LEVEL, digestUtil);
  }

  public FastCDCChunker(int minSize, int avgSize, int maxSize, int normalization, DigestUtil digestUtil) {
    checkArgument(minSize > 0, "minSize must be positive");
    checkArgument(avgSize >= minSize, "avgSize must be >= minSize");
    checkArgument(maxSize >= avgSize, "maxSize must be >= avgSize");
    checkArgument(normalization >= 0 && normalization <= 3, "normalization must be 0-3");

    this.minSize = minSize;
    this.avgSize = avgSize;
    this.maxSize = maxSize;
    this.digestUtil = digestUtil;

    // Mask selection matches fastcdc-go: masks[bits + normalization - 3] and masks[bits - normalization - 3]
    int bits = (int) Math.round(Math.log(avgSize) / Math.log(2));
    this.maskS = MASKS[bits + normalization - 3];
    this.maskL = MASKS[bits - normalization - 3];
  }

  public ImmutableList<ChunkData> chunk(InputStream input) throws IOException {
    List<ChunkData> chunks = new ArrayList<>();
    byte[] buf = new byte[maxSize * 2];
    int cursor = 0;
    int end = 0;
    boolean eof = false;

    while (true) {
      int available = end - cursor;
      if (available < maxSize && !eof) {
        if (cursor > 0 && available > 0) {
          System.arraycopy(buf, cursor, buf, 0, available);
        }
        cursor = 0;
        end = available;

        while (end < buf.length) {
          int n = input.read(buf, end, buf.length - end);
          if (n == -1) {
            eof = true;
            break;
          }
          end += n;
        }
        available = end - cursor;
      }

      if (available == 0) {
        break;
      }

      int chunkLen = cut(buf, cursor, available);
      ByteString data = ByteString.copyFrom(buf, cursor, chunkLen);
      Digest digest = digestUtil.compute(buf, cursor, chunkLen);
      chunks.add(new ChunkData(data, digest));
      cursor += chunkLen;
    }

    return ImmutableList.copyOf(chunks);
  }

  private int cut(byte[] buf, int off, int len) {
    if (len <= minSize) {
      return len;
    }

    int n = Math.min(len, maxSize);
    long fp = 0;
    int i = minSize;

    int center = Math.min(n, avgSize);
    for (; i < center; i++) {
      fp = (fp << 1) + GEAR[buf[off + i] & 0xFF];
      if ((fp & maskS) == 0) {
        return i + 1;
      }
    }

    for (; i < n; i++) {
      fp = (fp << 1) + GEAR[buf[off + i] & 0xFF];
      if ((fp & maskL) == 0) {
        return i + 1;
      }
    }

    return n;
  }

  /** Returns chunk lengths without computing digests. */
  int[] chunkBoundaries(byte[] data) {
    List<Integer> boundaries = new ArrayList<>();
    int offset = 0;
    while (offset < data.length) {
      int len = cut(data, offset, data.length - offset);
      boundaries.add(len);
      offset += len;
    }
    return boundaries.stream().mapToInt(Integer::intValue).toArray();
  }
